import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {chromium} from 'playwright'
import {PerspectiveCamera,Vector3} from 'three'
const browser=await chromium.launch({channel:'chrome',args:['--enable-unsafe-swiftshader','--use-angle=swiftshader']})
try{
 const page=await browser.newPage({viewport:{width:1440,height:940}})
 const errors=[]
 page.on('pageerror',error=>errors.push(error.message))
 page.on('console',message=>{if(message.type()==='error') errors.push(message.text())})
 await page.goto(process.env.LAB_URL||'http://127.0.0.1:5173/')
 const button=(name)=>page.getByRole('button',{name,exact:true})
 const status=page.getByRole('status')
 const part=(id)=>page.locator('.inventory .part').filter({has:page.locator('.part-copy b').filter({hasText:new RegExp('^'+id+' ')})})
 const canvas=page.locator('.scene canvas')
 await canvas.waitFor()
 await button('▶ 开始仿真').click()
 assert.match(await status.innerText(),/先完成电路/)
 await button('俯视').click()
 await page.waitForTimeout(350)
 const rect=await canvas.boundingBox()
 const camera=new PerspectiveCamera(42,rect.width/rect.height,.2,550)
 camera.position.set(5,128,1.01);camera.lookAt(5,0,1);camera.updateMatrixWorld()
 const xy=(col,z,rail=false)=>{ const v=new Vector3((15.5-col-(rail?.5:0))*2.54,.02,z).project(camera);return {x:(v.x+1)*rect.width/2,y:(1-v.y)*rect.height/2} }
 const clickHole=async (c,z,rail=false)=>{const p=xy(c,z,rail);await page.mouse.click(rect.x+p.x,rect.y+p.y)}
 await clickHole(27,-12.7)
 assert.match(await page.locator('.node-detail').innerText(),/a27 · U27 · 5 个孔导通/)
 const q=part('Q1')
 const qxy=xy(23,-7.62)
 await q.dragTo(canvas,{targetPosition:qxy})
 assert.match(await status.innerText(),/Q1 已插入/)
 await part('W1').click()
 await clickHole(23,-20.32,true)
 await clickHole(23,-12.7)
 assert.match(await status.innerText(),/W1 已插入/)
 await page.waitForTimeout(340)
 const a23=xy(23,-12.7), b23=xy(23,-10.16)
 await page.mouse.move(rect.x+a23.x,rect.y+a23.y)
 await page.mouse.down()
 await page.mouse.move(rect.x+b23.x,rect.y+b23.y,{steps:8})
 await page.mouse.up()
 assert.match(await status.innerText(),/W1 已插入.*b23/)
 await page.getByTitle('撤销').click()
 assert.match(await page.locator('.pins').innerText(),/a23/)
 await page.getByTitle('重做').click()
 assert.match(await page.locator('.pins').innerText(),/b23/)
 await page.getByTitle('移动端点 2').click()
 await page.locator('#hole-pick').selectOption('a23')
 await button('插入').click()
 assert.match(await status.innerText(),/a23/)
 const lists=[['Q2','W2'],['R1','R2','R7','R8'],['LED1','LED2'],['R3','R4','C1','C2','W3','W4','W5','W6'],['D1','D2','W7','W8','R6','R5','C3','S1','W9'],['P1']]
 for(const [i,list] of lists.entries()){
  for(const id of list){await part(id).click();if(id==='Q2'){await button('观看插入').click();await button('关闭示范').waitFor();await button('关闭示范').click()}await button('用推荐孔位').click();assert.match(await status.innerText(),new RegExp(id+' 已插入'))}
  await button(i===5?'检查本步':'检查本步并继续 →').click()
  assert.match(await status.innerText(),/通过检查|电气连接与讲义/)
 }
 await button('▶ 开始仿真').click()
 assert.match(await page.locator('.states .on').innerText(),/LED1/)
 await button('按下 S1').click()
 assert.match(await page.locator('.states .on').innerText(),/LED2/)
 // Hold the 3D momentary switch, then release it without a second transition.
 const bounds=await canvas.boundingBox()
 camera.aspect=bounds.width/bounds.height;camera.updateProjectionMatrix()
 const sw=new Vector3((15.5-29.5)*2.54,5.2,12.7).project(camera)
 await page.mouse.move(bounds.x+(sw.x+1)*bounds.width/2,bounds.y+(1-sw.y)*bounds.height/2)
 await page.mouse.down()
 assert.match(await page.locator('.states .on').innerText(),/LED1/)
 await page.mouse.up()
 assert.match(await page.locator('.states .on').innerText(),/LED1/)
 await button('自由').click()
 await page.waitForTimeout(650)
 await mkdir('artifacts',{recursive:true})
 await page.screenshot({path:'artifacts/lab.png'})
 await button('▤ 原理图').click()
 assert.ok(await page.getByRole('dialog').isVisible())
 await button('关闭').click()
 await button('自由搭建').click()
 await part('D1').click()
 await button('反向 / 180°').click()
 await button('电路检查').click()
 assert.match(await page.locator('.error').innerText(),/D1/)
 page.once('dialog',dialog=>dialog.accept())
 await button('重置').click()
 assert.match(await page.locator('.app-foot').innerText(),/0 个元件/)
 assert.deepEqual(errors,[])
 console.log('Chrome: 3D hole hit, drag/drop, wiring, undo/redo, all six lessons, diode reversal, LED toggle, schematic and reset passed.')
} finally {await browser.close()}
